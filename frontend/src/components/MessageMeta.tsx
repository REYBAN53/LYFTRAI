import type { ChatMetadata } from "../api/types";
import { formatNumber } from "../lib/format";
import { BoltIcon, KeyIcon, SparkIcon } from "./icons";

/**
 * Per-request metadata. Each data-testid element contains exactly the contract value
 * (labels and icons sit outside those elements).
 */
export function MessageMeta({ metadata }: { metadata: ChatMetadata }) {
  const cached = metadata.resolution_source === "LLM_CACHE";
  return (
    <div className="meta" aria-label="Response metadata">
      <span className={`chip chip-source ${cached ? "is-cache" : "is-live"}`} title={cached ? "Served from LiteLLM response cache" : "Generated by the model"}>
        {cached ? <BoltIcon width={12} height={12} /> : <SparkIcon width={12} height={12} />}
        <span data-testid="meta-source">{metadata.resolution_source}</span>
      </span>
      <span className="chip chip-model" title="Model">
        <span data-testid="meta-model">{metadata.model}</span>
      </span>
      <span className="chip" title="Server-measured latency">
        <span data-testid="meta-latency">{`${metadata.latency_ms} ms`}</span>
      </span>
      <span className="chip" title="Input (prompt) tokens for this request">
        <span className="chip-label">in</span>
        <span data-testid="meta-input-tokens">{metadata.input_tokens}</span>
      </span>
      <span className="chip" title="Output (completion) tokens for this reply">
        <span className="chip-label">out</span>
        <span data-testid="meta-output-tokens">{metadata.output_tokens}</span>
      </span>
      {metadata.key_id && (
        <span
          className={`chip ${metadata.fallback_attempts > 0 ? "chip-warn" : ""}`}
          title={
            metadata.fallback_attempts > 0
              ? `${metadata.fallback_attempts} key(s) failed before ${metadata.key_id} answered`
              : `Answered by ${metadata.key_id}`
          }
        >
          <KeyIcon width={12} height={12} />
          <span>{metadata.key_id}</span>
          {metadata.fallback_attempts > 0 && (
            <span className="chip-label">
              · {formatNumber(metadata.fallback_attempts)} failover{metadata.fallback_attempts > 1 ? "s" : ""}
            </span>
          )}
        </span>
      )}
    </div>
  );
}
